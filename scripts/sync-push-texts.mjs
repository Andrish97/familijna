// Teksty powiadomień push aplikacji (E29) dla funkcji Edge push-send — kopia
// sekcji `push` z web/shared/translation/<lang>/server.js. Źródłem są
// tłumaczenia; po zmianie: node scripts/sync-push-texts.mjs
// (test unit pushContent.test.js pilnuje zgodności).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadDicts } from "./i18n-parts.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const TARGET = path.join(root, "supabase/functions/_shared/push-app-texts.js");

function flatten(obj, prefix, out) {
  for (const [k, v] of Object.entries(obj)) {
    const key = `${prefix}.${k}`;
    if (v && typeof v === "object") flatten(v, key, out);
    else if (typeof v === "string") out[key] = v;
    else throw new Error(`push: nieobsługiwana wartość ${key}`);
  }
  return out;
}

export async function buildTexts() {
  const dicts = await loadDicts();
  const out = {};
  for (const lang of ["pl", "en", "uk"]) {
    if (!dicts[lang]?.push) throw new Error(`Brak sekcji push w ${lang}`);
    out[lang] = flatten(dicts[lang].push, "push", {});
  }
  return out;
}

export function renderModule(texts) {
  return "// Generated by scripts/sync-push-texts.mjs from web/shared/translation. Do not edit.\n"
    + `export const PUSH_APP_TEXTS = ${JSON.stringify(texts, null, 1)};\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  fs.writeFileSync(TARGET, renderModule(await buildTexts()));
  console.log("zapisano", path.relative(root, TARGET));
}
